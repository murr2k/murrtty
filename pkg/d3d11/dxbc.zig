//! murrtty's build-time shader compiler (roadmap 7.8, DxbcStep): the
//! Direct3D 11 renderer's HLSL to DXBC with System32's d3dcompiler_47.dll,
//! run on the build machine (Windows, for murrtty; DXBC is the same for
//! x64 and ARM64). The renderer then embeds the bytecode and compiles
//! nothing at run time but custom shaders.
//!
//! Usage: murrtty-dxbc <out dir> (--program <name> <vs> <ps|-> (--file <path>)...)...
//!
//! A program's files are joined as the renderer joins them at run time,
//! each after the first under `#line 1 "<its name>"`. Writes
//! `<name>.vs.dxbc` and `<name>.ps.dxbc` per program (no pixel stage for
//! `-`), and `dxbc.zig`, which embeds them.
const std = @import("std");
const compiler = @import("compiler.zig");

const Program = struct {
    name: [:0]const u8,
    vs: [:0]const u8,
    ps: ?[:0]const u8,
    text: std.ArrayList(u8) = .empty,
    files: usize = 0,
};

pub fn main(init: std.process.Init) !void {
    const alloc = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(alloc);
    if (args.len < 2) usage();
    const out = args[1];
    try std.Io.Dir.cwd().createDirPath(io, out);

    var programs: std.ArrayList(Program) = .empty;
    var i: usize = 2;
    while (i < args.len) {
        if (std.mem.eql(u8, args[i], "--program")) {
            if (i + 3 >= args.len) usage();
            const ps = args[i + 3];
            try programs.append(alloc, .{
                .name = args[i + 1],
                .vs = args[i + 2],
                .ps = if (std.mem.eql(u8, ps, "-")) null else ps,
            });
            i += 4;
        } else if (std.mem.eql(u8, args[i], "--file")) {
            if (i + 1 >= args.len or programs.items.len == 0) usage();
            const p = &programs.items[programs.items.len - 1];
            const path = args[i + 1];
            const text = try std.Io.Dir.cwd().readFileAlloc(io, path, alloc, .limited(4 << 20));
            if (p.files > 0) {
                try p.text.appendSlice(alloc, "\n#line 1 \"");
                try p.text.appendSlice(alloc, std.fs.path.basename(path));
                try p.text.appendSlice(alloc, "\"\n");
            }
            try p.text.appendSlice(alloc, text);
            p.files += 1;
            i += 2;
        } else usage();
    }

    var zig: std.ArrayList(u8) = .empty;
    try zig.appendSlice(alloc,
        \\//! Generated by murrtty's dxbc tool (pkg/d3d11/dxbc.zig, roadmap 7.8):
        \\//! the Direct3D 11 renderer's programs, compiled at build time.
        \\pub const built = true;
        \\
    );
    for (programs.items) |p| {
        try compileTo(alloc, io, out, p, p.vs, "vs", "vs_5_0");
        if (p.ps) |ps| try compileTo(alloc, io, out, p, ps, "ps", "ps_5_0");
        try zig.print(alloc, "pub const {s}: [2][]const u8 = .{{ @embedFile(\"{s}.vs.dxbc\"), ", .{ p.name, p.name });
        if (p.ps != null) {
            try zig.print(alloc, "@embedFile(\"{s}.ps.dxbc\") }};\n", .{p.name});
        } else {
            try zig.appendSlice(alloc, "\"\" };\n");
        }
    }
    const zig_path = try std.fs.path.join(alloc, &.{ out, "dxbc.zig" });
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = zig_path, .data = zig.items });
}

fn compileTo(
    alloc: std.mem.Allocator,
    io: std.Io,
    out: []const u8,
    p: Program,
    entry: [:0]const u8,
    stage: []const u8,
    target: [:0]const u8,
) !void {
    var messages: std.ArrayList(u8) = .empty;
    const code = compiler.compile(p.text.items, p.name, entry, target, compiler.OPTIMIZATION_LEVEL3, &messages, alloc) catch |err| {
        std.log.err("{s} {s} ({s}): {t}\n{s}", .{ p.name, entry, target, err, messages.items });
        std.process.exit(1);
    };
    defer code.deinit();
    const name = try std.fmt.allocPrint(alloc, "{s}.{s}.dxbc", .{ p.name, stage });
    const path = try std.fs.path.join(alloc, &.{ out, name });
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = path, .data = code.bytes() });
}

fn usage() noreturn {
    std.log.err("usage: murrtty-dxbc <out dir> (--program <name> <vs> <ps|-> (--file <path>)...)...", .{});
    std.process.exit(1);
}
